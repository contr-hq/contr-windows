#!/usr/bin/env python3
"""Builds the Contr Icons font and its C# glyph table from assets/icons.

Usage: uv run --with fonttools==4.60.1 scripts/build-icon-font.py

assets/icons/icons.json pins every icon's code point; add an icon at the end so existing glyphs keep theirs.
"""

import json
import pathlib
import re
import xml.etree.ElementTree as ET

from fontTools.fontBuilder import FontBuilder
from fontTools.misc.timeTools import timestampFromString
from fontTools.pens.cu2quPen import Cu2QuPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.svgLib.path import parse_path

UNITS_PER_EM = 2048
# A fixed date, so the same SVGs build the same bytes.
BUILT = timestampFromString("Tue Oct 20 00:00:00 2026")
SVG = "{http://www.w3.org/2000/svg}"

root = pathlib.Path(__file__).resolve().parent.parent
icons = root / "assets" / "icons"
font_path = root / "src" / "App" / "Contr.App" / "Assets" / "Fonts" / "ContrIcons.ttf"
table_path = root / "src" / "Shared" / "Contr.UI.Common" / "Icons" / "ContrIcons.g.cs"

manifest = json.loads((icons / "icons.json").read_text(encoding="utf-8"))
family = manifest["family"]


def outline(svg_file: pathlib.Path):
    """The icon's paths, its view box scaled to the em and its y axis flipped to point up."""
    svg = ET.parse(svg_file).getroot()
    _, _, width, height = (float(value) for value in svg.get("viewBox").split())
    scale = UNITS_PER_EM / max(width, height)
    pen = TTGlyphPen(None)
    flipped = TransformPen(
        Cu2QuPen(pen, max_err=1.0, reverse_direction=True), (scale, 0, 0, -scale, 0, UNITS_PER_EM))
    for path in svg.iter(f"{SVG}path"):
        # SVG lets a path draw on after Z from the closed subpath's start; fontTools wants a move first.
        data = re.sub(r"([zZ])\s*(?=[^mMzZ\s])", r"\1m0 0", path.get("d"))
        parse_path(data, flipped)
    return pen.glyph()


glyph_order = [".notdef"]
glyphs = {".notdef": TTGlyphPen(None).glyph()}
cmap = {}
for icon in manifest["icons"]:
    name = icon["name"]
    glyph_order.append(name)
    glyphs[name] = outline(icons / "svg" / f"{name}.svg")
    cmap[int(icon["codepoint"], 16)] = name

builder = FontBuilder(UNITS_PER_EM, isTTF=True)
builder.setupGlyphOrder(glyph_order)
builder.setupCharacterMap(cmap)
builder.setupGlyf(glyphs)
glyf = builder.font["glyf"]
builder.setupHorizontalMetrics(
    {name: (UNITS_PER_EM, getattr(glyf[name], "xMin", 0)) for name in glyph_order})
builder.setupHorizontalHeader(ascent=UNITS_PER_EM, descent=0)
builder.setupNameTable({
    "familyName": family,
    "styleName": "Regular",
    "copyright": "Icons from Fluent UI System Icons, Copyright (c) 2020 Microsoft Corporation, MIT licence",
})
builder.setupOS2(
    sTypoAscender=UNITS_PER_EM, sTypoDescender=0, sTypoLineGap=0,
    usWinAscent=UNITS_PER_EM, usWinDescent=0, achVendID="CNTR")
builder.setupPost()
builder.font.recalcTimestamp = False
builder.font["head"].created = BUILT
builder.font["head"].modified = BUILT
font_path.parent.mkdir(parents=True, exist_ok=True)
builder.save(font_path)

lines = [
    "// <auto-generated/> scripts/build-icon-font.py writes this file from assets/icons/icons.json.",
    "",
    "namespace Contr.UI.Common.Icons;",
    "",
    f"/// <summary>The glyphs of the {family} font by name; a FontIcon draws them with ContrIconsFontFamily.</summary>",
    "public static class ContrIcons",
    "{",
]
for index, icon in enumerate(manifest["icons"]):
    if index:
        lines.append("")
    lines.append(f"    public const string {icon['name']} = \"\\u{icon['codepoint']}\";")
lines.append("}")
table_path.parent.mkdir(parents=True, exist_ok=True)
table_path.write_text("\n".join(lines) + "\n", encoding="utf-8")

print(f"{font_path.relative_to(root)}: {len(cmap)} glyphs")
